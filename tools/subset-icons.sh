# Builds the Material Symbols subsets Caelum embeds: only the glyphs named in
# crates/caelum-ui/fonts/icons.txt, pinned to static Rounded weight 400, once
# unfilled and once filled (Caelestia's `fill: 1` icons, as family
# "Material Symbols Rounded Filled"). Also generates ui/icons.slint and
# src/icons.rs, which map each name to its codepoint.
# Usage: tools/subset-icons.sh [path/to/MaterialSymbolsRounded[...].ttf]
set -euo pipefail
cd "$(dirname "$0")/.."

src=${1:-"/usr/share/fonts/ttf-material-symbols-variable/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf"}
dir=crates/caelum-ui/fonts
tmp=$(mktemp --suffix=.ttf)
trap 'rm -f "$tmp"' EXIT

# Name -> codepoint from the font's own cmap, so icons.txt holds readable names.
mapfile -t pairs < <(python3 -I - "$src" "$dir/icons.txt" <<'PY'
import sys
from fontTools.ttLib import TTFont
cmap = {name: cp for cp, name in TTFont(sys.argv[1]).getBestCmap().items()}
for line in open(sys.argv[2]):
    name = line.split("#")[0].strip()
    if not name:
        continue
    if name not in cmap:
        sys.exit(f"unknown icon: {name}")
    print(f"{name} {cmap[name]:04x}")
PY
)

unicodes=$(printf '%s\n' "${pairs[@]}" | awk '{print "U+" $2}' | paste -sd,)
pyftsubset "$src" --unicodes="$unicodes" --layout-features= --no-hinting --output-file="$tmp"
fonttools varLib.instancer "$tmp" FILL=0 GRAD=0 opsz=24 wght=400 -o "$dir/material-symbols-subset.ttf" -q
fonttools varLib.instancer "$tmp" FILL=1 GRAD=0 opsz=24 wght=400 -o "$dir/material-symbols-filled-subset.ttf" -q
# A family of its own, so Slint can pick the filled glyphs by name.
python3 -I - "$dir/material-symbols-filled-subset.ttf" <<'PY'
import sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1])
for rec in f["name"].names:
    if rec.nameID in (1, 4, 16):
        rec.string = "Material Symbols Rounded Filled"
    elif rec.nameID == 6:
        rec.string = "MaterialSymbolsRounded-Filled"
f.save(sys.argv[1])
PY

{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Generated by tools/subset-icons.sh from fonts/icons.txt. Do not edit."
    echo 'import "../fonts/material-symbols-subset.ttf";'
    echo 'import "../fonts/material-symbols-filled-subset.ttf";'
    echo
    echo "export global Icons {"
    echo '    out property <string> family: "Material Symbols Rounded";'
    echo '    out property <string> family-filled: "Material Symbols Rounded Filled";'
    for p in "${pairs[@]}"; do
        read -r name cp <<<"$p"
        echo "    out property <string> ${name//_/-}: \"\\u{$cp}\";"
    done
    echo "}"
} > crates/caelum-ui/ui/icons.slint

{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Generated by tools/subset-icons.sh from fonts/icons.txt. Do not edit."
    echo
    echo "/// The glyph for a Material Symbols name, empty for one not in fonts/icons.txt."
    echo "pub fn icon(name: &str) -> &'static str {"
    echo "    match name {"
    for p in "${pairs[@]}"; do
        read -r name cp <<<"$p"
        echo "        \"$name\" => \"\\u{$cp}\","
    done
    echo '        _ => "",'
    echo "    }"
    echo "}"
} > crates/caelum-ui/src/icons.rs
ls -l "$dir"/material-symbols-*subset.ttf
